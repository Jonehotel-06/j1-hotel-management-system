"""Private object store for the TV rooms gallery (Backblaze B2 / S3-compatible).

Why this exists (2026-11-22 repair — Rooms Gallery media persistence)
====================================================================
The gallery's own store used to be filesystem-only. That is durable exactly
when the directory ``TV_GALLERY_STORAGE_ROOT`` resolves to is a mounted,
persistent volume. Production runs the API in a container whose filesystem is
replaced on every deploy, so when no volume is mounted at that path the files
are lost while the database rows survive: the catalog still lists the media and
every rendition answers 404. ``storage.py`` documents the 2026-11-20 production
evidence of exactly that failure (media ids 1-9 listed, all 404).

This module adds the OTHER durable home the project already relies on for all
public media: an S3-compatible object store (Backblaze B2 — the same provider
``config/settings/base.py`` configures through django-storages). Object storage
is independent of the application's deployment and source-code lifecycle, so
uploads survive deploys, rebuilds, restarts and container replacement without a
mounted volume.

Storage contract (same shape as ``storage.py``)
===============================================
* Keys are opaque 32-hex names generated by the caller (``storage.save_chunks``);
  this module only prefixes them with ``TV_GALLERY_OBJECT_PREFIX`` (default
  ``tv-gallery``). A key never becomes a filesystem path here, so no traversal
  is possible, and an existing key keeps resolving to the same object forever.
* ``put`` / ``download`` / ``stat`` / ``delete`` / ``list_keys`` operate ONLY on
  objects under the gallery prefix. Nothing else in the bucket is touched.
* The store is PRIVATE. Objects are never given public URLs and are never served
  from the bucket: the gallery API streams bytes through its own routes, so
  bucket privacy is preserved regardless of the bucket's policy.

Configuration (environment; evaluated per call so a container can be fixed
without a code change — the same pattern ``storage.py`` uses)
=============================================================
    TV_GALLERY_BUCKET_NAME             dedicated PRIVATE bucket (required)
    TV_GALLERY_BUCKET_KEY_ID           access key id       (default: BACKBLAZE_KEY_ID)
    TV_GALLERY_BUCKET_APPLICATION_KEY  application key     (default: BACKBLAZE_APPLICATION_KEY)
    TV_GALLERY_BUCKET_ENDPOINT         S3 endpoint         (default: BACKBLAZE_ENDPOINT)
    TV_GALLERY_BUCKET_REGION           region              (default: parsed from the endpoint, then BACKBLAZE_REGION)
    TV_GALLERY_OBJECT_PREFIX           object prefix       (default: "tv-gallery")

``TV_GALLERY_BUCKET_*`` exists so the gallery can use its OWN bucket: the media
bucket configured through ``BACKBLAZE_*`` is expected to be publicly readable
(settings/base.py serves media straight off it), and gallery originals must
stay private until the API publishes a rendition.

No credentials are ever logged or returned; ``describe()`` reports only their
presence.
"""
from __future__ import annotations

import logging
import os
import re
from threading import Lock
from typing import Dict, Iterable, List, Optional, Tuple

from django.conf import settings

logger = logging.getLogger(__name__)

#: Same key shape ``storage.py`` enforces; enforced again here so nothing but a
#: valid gallery key can ever be prefixed and sent to the object store.
_KEY = re.compile(r"^[0-9a-f]{32}$")

DEFAULT_PREFIX = "tv-gallery"
#: Credentials are read once per call from the environment, mirroring
#: ``storage._configured_root``. Nothing here caches secrets.
_CLIENT: Optional[object] = None
_CLIENT_LOCK = Lock()


class ObjectStoreUnavailable(Exception):
    """Object storage is misconfigured or unusable; the caller must not guess.

    Carries an operator-facing message. ``storage.resolve`` maps connection
    faults to ``FILE_STORAGE_UNAVAILABLE`` (HTTP 503) and missing objects to
    ``FILE_MISSING`` (404), so this exception is for CONFIGURATION problems and
    is raised before any data is written.
    """

    def __init__(self, message: str):
        super().__init__(message)
        self.message = message


def _setting(name: str, fallback_env: str, default: str = "") -> str:
    """TV_GALLERY_BUCKET_* first, then its BACKBLAZE_* fallback, then default."""
    direct = (os.environ.get(name) or "").strip()
    if direct:
        return direct
    return (os.environ.get(fallback_env) or "").strip() or default


def bucket_name() -> str:
    return _setting("TV_GALLERY_BUCKET_NAME", "TV_GALLERY_BUCKET_NAME")


def object_prefix() -> str:
    raw = _setting("TV_GALLERY_OBJECT_PREFIX", "TV_GALLERY_OBJECT_PREFIX", DEFAULT_PREFIX)
    cleaned = raw.strip().strip("/")
    return cleaned or DEFAULT_PREFIX


def region_from_endpoint(endpoint: str) -> str:
    """"https://s3.us-west-004.backblazeb2.com" -> "us-west-004" (mirrors base.py)."""
    match = re.search(r"s3\.([^./]+)\.backblazeb2\.com", endpoint or "")
    return match.group(1) if match else ""


def describe() -> Dict[str, object]:
    """Configuration report for operators. Presence only — never secret values."""
    ready, detail = configured()
    return {
        "ready": ready,
        "detail": detail,
        "bucket": bucket_name(),
        "prefix": object_prefix(),
        "endpoint": _setting("TV_GALLERY_BUCKET_ENDPOINT", "BACKBLAZE_ENDPOINT",
                             "https://s3.us-east-005.backblazeb2.com"),
        "region": _setting("TV_GALLERY_BUCKET_REGION", "BACKBLAZE_REGION") or "",
        "credentials": ("set" if _setting("TV_GALLERY_BUCKET_KEY_ID", "BACKBLAZE_KEY_ID") else "missing"),
    }


def configured() -> Tuple[bool, str]:
    """(ready, reason). ``ready`` requires a bucket, credentials and boto3."""
    try:
        import boto3  # noqa: F401
        import botocore  # noqa: F401
    except ImportError:
        return False, "boto3/django-storages are not installed in this environment."
    if not bucket_name():
        return False, (
            "Object storage is selected but TV_GALLERY_BUCKET_NAME is not set. "
            "Configure a dedicated PRIVATE bucket (TV_GALLERY_BUCKET_NAME plus "
            "TV_GALLERY_BUCKET_KEY_ID / TV_GALLERY_BUCKET_APPLICATION_KEY, or the "
            "BACKBLAZE_* equivalents) or switch TV_GALLERY_STORAGE_BACKEND to 'fs'."
        )
    if not _setting("TV_GALLERY_BUCKET_KEY_ID", "BACKBLAZE_KEY_ID") or not _setting(
        "TV_GALLERY_BUCKET_APPLICATION_KEY", "BACKBLAZE_APPLICATION_KEY"
    ):
        return False, (
            "Object storage is selected but bucket credentials are missing "
            "(TV_GALLERY_BUCKET_KEY_ID / TV_GALLERY_BUCKET_APPLICATION_KEY or "
            "BACKBLAZE_KEY_ID / BACKBLAZE_APPLICATION_KEY)."
        )
    return True, "%s/%s" % (bucket_name(), object_prefix())


def _endpoint() -> str:
    endpoint = _setting("TV_GALLERY_BUCKET_ENDPOINT", "BACKBLAZE_ENDPOINT",
                        "https://s3.us-east-005.backblazeb2.com")
    if not re.match(r"^https?://", endpoint):
        endpoint = "https://" + endpoint
    # An http:// endpoint would send the application key in the clear.
    return re.sub(r"^http://", "https://", endpoint)


def _region() -> str:
    explicit = _setting("TV_GALLERY_BUCKET_REGION", "BACKBLAZE_REGION")
    if explicit:
        return explicit
    return region_from_endpoint(_endpoint()) or "us-east-005"


def client():
    """A lazily built, process-cached boto3 S3 client for the gallery bucket.

    Mirrors the client configuration ``config/settings/base.py`` uses for the
    media bucket: virtual-host addressing, s3v4 signatures, checksums only when
    required (botocore >= 1.36 sends x-amz-sdk-checksum-algorithm on every
    PutObject and B2 answers 400 InvalidArgument), bounded timeouts so a stalled
    object store cannot hang a worker forever.
    """
    global _CLIENT
    with _CLIENT_LOCK:
        if _CLIENT is not None:
            return _CLIENT
        ready, reason = configured()
        if not ready:
            raise ObjectStoreUnavailable(reason)
        try:
            import boto3
            from botocore.config import Config as BotocoreConfig
        except ImportError as exc:  # pragma: no cover - configured() already checked
            raise ObjectStoreUnavailable("boto3 is not installed: %s" % exc) from exc
        _CLIENT = boto3.client(
            "s3",
            endpoint_url=_endpoint(),
            region_name=_region(),
            aws_access_key_id=_setting("TV_GALLERY_BUCKET_KEY_ID", "BACKBLAZE_KEY_ID"),
            aws_secret_access_key=_setting("TV_GALLERY_BUCKET_APPLICATION_KEY", "BACKBLAZE_APPLICATION_KEY"),
            config=BotocoreConfig(
                signature_version="s3v4",
                s3={"addressing_style": "virtual"},
                request_checksum_calculation="when_required",
                response_checksum_validation="when_required",
                connect_timeout=5,
                read_timeout=120,
                retries={"max_attempts": 3, "mode": "standard"},
            ),
        )
        return _CLIENT


def _prefixed(key: str) -> str:
    if not _KEY.fullmatch(str(key or "")):
        raise ValueError("Invalid gallery storage key")
    return "%s/%s" % (object_prefix(), key)


def put(key: str, source) -> int:
    """Upload ``source`` (a binary file object) as ``key``; returns its size.

    The bytes must already be complete and size-checked (``storage.save_chunks``
    owns the limit); this call publishes exactly what it is given. Only a valid
    gallery key is accepted.
    """
    import boto3.s3.transfer as s3transfer  # noqa: F401 - documents the mechanism

    name = _prefixed(key)
    size = source.seek(0, os.SEEK_END)
    source.seek(0)
    client().upload_fileobj(source, bucket_name(), name)
    logger.info("Gallery object stored: prefix=%s key=%s bytes=%d", object_prefix(), key, size)
    return size


def download(key: str, destination) -> int:
    """Download ``key`` into a binary file object; returns the object size.

    Raises FileNotFoundError when the object does not exist so callers can
    distinguish a missing key from a broken store without parsing boto errors.
    """
    name = _prefixed(key)
    try:
        response = client().get_object(Bucket=bucket_name(), Key=name)
    except FileNotFoundError:
        raise
    except Exception as exc:
        parsed = getattr(exc, "response", None) or {}
        status = parsed.get("ResponseMetadata", {}).get("HTTPStatusCode")
        if status == 404 or parsed.get("Error", {}).get("Code") in ("NoSuchKey", "NotFound"):
            raise FileNotFoundError(name) from exc
        raise
    body = response["Body"]
    written = 0
    try:
        for chunk in body.iter_chunks(chunk_size=1024 * 1024):
            destination.write(chunk)
            written += len(chunk)
    finally:
        body.close()
    return written


def stat(key: str) -> Optional[int]:
    """The stored size of ``key``, or None when the object does not exist."""
    name = _prefixed(key)
    try:
        response = client().head_object(Bucket=bucket_name(), Key=name)
    except Exception as exc:
        parsed = getattr(exc, "response", None) or {}
        status = parsed.get("ResponseMetadata", {}).get("HTTPStatusCode")
        if status == 404 or parsed.get("Error", {}).get("Code") in ("NoSuchKey", "NotFound", "404"):
            return None
        raise
    return int(response.get("ContentLength") or 0)


def delete(key: str) -> None:
    """Remove ``key``. Missing objects delete cleanly (S3 semantics)."""
    try:
        client().delete_object(Bucket=bucket_name(), Key=_prefixed(key))
    except ValueError:
        # A malformed key names no object; removal is a no-op, never a path.
        return


def list_keys() -> List[str]:
    """Every gallery key stored under the prefix (key names WITHOUT the prefix)."""
    import boto3  # configured() already proved boto3 imports cleanly

    keys: List[str] = []
    paginator = client().get_paginator("list_objects_v2")
    for page in paginator.paginate(Bucket=bucket_name(), Prefix=object_prefix() + "/"):
        for entry in page.get("Contents", []):
            name = str(entry.get("Key") or "")
            stripped = name[len(object_prefix()) + 1:]
            if _KEY.fullmatch(stripped):
                keys.append(stripped)
    return keys


def list_keys_with_age() -> List[Tuple[str, Optional[float]]]:
    """Every gallery key with its last-modified epoch seconds (cleanup support).

    Mirrors ``list_keys`` but also carries the object's ``LastModified`` so the
    orphan-cleanup command can honour its minimum-age rule on the object layer
    exactly as it does on the filesystem.
    """
    import boto3  # configured() already proved boto3 imports cleanly

    pairs: List[Tuple[str, Optional[float]]] = []
    paginator = client().get_paginator("list_objects_v2")
    for page in paginator.paginate(Bucket=bucket_name(), Prefix=object_prefix() + "/"):
        for entry in page.get("Contents", []):
            name = str(entry.get("Key") or "")
            stripped = name[len(object_prefix()) + 1:]
            if not _KEY.fullmatch(stripped):
                continue
            modified = entry.get("LastModified")
            timestamp = modified.timestamp() if modified is not None else None
            pairs.append((stripped, timestamp))
    return pairs


def probe() -> Tuple[bool, str]:
    """A real put/get/delete round-trip with a tiny object. Never raises."""
    import uuid

    probe_key = uuid.uuid4().hex
    import io

    payload = b"jone-gallery-object-probe"
    try:
        with io.BytesIO(payload) as source:
            put(probe_key, source)
        with io.BytesIO() as sink:
            size = download(probe_key, sink)
            if sink.getvalue() != payload:
                return False, "Object round-trip returned different bytes."
        delete(probe_key)
        return True, "put/get/delete round-trip succeeded (%d bytes)." % size
    except Exception as exc:
        return False, "Object round-trip failed: %s" % exc


def reset_cached_client() -> None:
    """Forget the cached client (used after configuration changes and in tests)."""
    global _CLIENT
    with _CLIENT_LOCK:
        _CLIENT = None
